"""Build src/lib/scenes/generated/scene-data.ts from the sourced dimension files and the fab-flow YAML.

Inputs (read-only):
  assets3d/crystal.toml, lnoi.toml, mzm-die.toml, process.toml   dimensions with provenance
  content/chapters/05-making/process-flow.yaml                    steps, parameters (PDims), materials

Output (deterministic, no timestamps):
  src/lib/scenes/generated/scene-data.ts   DIMS (per TOML file) and FLOW (the process-viewer steps)

Checks: every dimension row has a status; reported rows have a source and locator; template rows have a note;
derived rows have a formula; every step named in process.toml exists in the YAML.

usage: uv run assets3d/build_scene_data.py [--check]
"""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TOMLS = ["crystal", "lnoi", "mzm-die", "process"]
FLOW_YAML = ROOT / "content/chapters/05-making/process-flow.yaml"
OUT = ROOT / "src/lib/scenes/generated/scene-data.ts"
STATUSES = {"reported", "derived", "template", "na"}


def check_dim(where: str, d: object, errors: list[str]) -> None:
    if not isinstance(d, dict) or "value" not in d:
        return
    st = d.get("status")
    if st not in STATUSES:
        errors.append(f"{where}: status {st!r}")
    if st == "reported" and not (d.get("source") and d.get("locator")):
        errors.append(f"{where}: reported without source/locator")
    if st == "template" and not d.get("note"):
        errors.append(f"{where}: template without note")
    if st == "derived" and not (d.get("formula") or d.get("source")):
        errors.append(f"{where}: derived without formula")


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    errors: list[str] = []
    dims: dict[str, object] = {}
    for name in TOMLS:
        data = tomllib.loads((ROOT / "assets3d" / f"{name}.toml").read_text())
        for sec, rows in data.items():
            if sec == "meta" or not isinstance(rows, dict):
                continue
            for key, d in rows.items():
                check_dim(f"{name}.{sec}.{key}", d, errors)
        dims[name.replace("-die", "")] = data

    flow = yaml.safe_load(FLOW_YAML.read_text())
    by_id = {s["id"]: s for s in flow["steps"]}
    meta = dims["process"]["meta"]  # type: ignore[index]
    wanted: list[str] = []
    for sid in meta["steps_ridge_duv"] + meta["steps_strip_dlc"]:
        if sid not in by_id:
            errors.append(f"process.toml names unknown step {sid}")
        elif sid not in wanted:
            wanted.append(sid)
    order = [s["id"] for s in flow["steps"]]
    wanted.sort(key=order.index)
    steps = []
    for sid in wanted:
        s = by_id[sid]
        steps.append({k: s.get(k) for k in ["id", "phase", "name", "routes", "scale", "tool", "camera", "params", "duration", "physics", "note"] if k in s})
    out_flow = {
        "schema": flow.get("schema"),
        "id": flow.get("id"),
        "title": flow.get("title"),
        "date": str(flow.get("date")),
        "status": flow.get("status"),
        "routes": flow.get("routes"),
        "anchors": flow.get("anchors"),
        "materials": [m for m in flow.get("materials", []) if m.get("key") in ("ln", "dlc", "melt")],
        "steps": steps,
    }
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    body = (
        "// GENERATED by assets3d/build_scene_data.py from assets3d/{crystal,lnoi,mzm-die,process}.toml and\n"
        "// content/chapters/05-making/process-flow.yaml. Do not edit; edit the sources and rebuild.\n"
        "/* eslint-disable */\n"
        f"export const DIMS = {json.dumps(dims, indent=1, ensure_ascii=False)} as const;\n\n"
        f"export const FLOW = {json.dumps(out_flow, indent=1, ensure_ascii=False, default=str)} as const;\n"
    )
    if check_only:
        print(f"ok: {sum(len(v) for v in dims.values())} sections, {len(steps)} steps")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(steps)} steps, {len(body)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
